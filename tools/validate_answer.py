"""Grade a cheap model's answer against that run's `metrics.json` (EVAL-01).

WHY `tools/` AND NOT `scripts/`. This is not a pipeline stage. It runs *after*
the report, on a file the model produced; it has no `--spec`/`--out` contract;
it is never in `run_all`'s four-stage sequence; and `scripts/` is the directory
the agentskills runtime loads, the one `mypy scripts --strict` treats as the
frozen stage surface, and the one the contract tests enumerate. A fifth CLI
there would make `scripts/` mean two things. It also imports **nothing from
the skill** - it is a reader - so it needs no `sys.path` shim and no `common`
import, which is what makes the no-network proof a one-line AST check.

It reads `metrics.json` and NOTHING else. Not `charts.json`, not `report.md`,
not `series.csv`. The answer is graded against the same single source of truth
the report was written from (ANAL-06, `references/CONTRACTS.md` §2), which is
the only way "the model did not invent a number" is a mechanical claim rather
than a promise.

===========================================================================
THE NUMBER RULE, IN FULL (an unstated rule is a noisy check)
===========================================================================

1. The SOURCE SET is every numeric leaf of `metrics.json`, plus `as_of` and
   every `period.start` / `period.end` **as whole strings** - the dates
   themselves, not their components. A date is not a measurement.

2. For each source number `v` the ACCEPTED FORMS are precomputed and the list
   is CLOSED - it is a fixed set of spellings, not a tolerance:

       str(v)                      f"{v:+.1f}"        f"{v:,.1f}"
       f"{v:+}"                    f"{v:.1f}"         f"{v:,.0f}"
       str(int(v))  (integral v)   str(round(v, 0))   str(round(v, 1))

   plus a SPACE-grouped variant of each grouped form, generated by replacing
   `,` with U+00A0 and then with U+0020 (so `1 720 628` is a spelling of
   1720628). **There is no tolerance band.** A band is precisely what lets a
   wrong number through: if 16.7 passes because 16.6 would also pass, the
   check is decorative.

3. TOKENISATION is one regex: an optional `+`/`-`, a digit, then digits with
   optional `,` / U+00A0 / space grouping, then an optional `.` plus digits,
   then an optional `%`. The line number and character offset of every match
   are captured so a failure can point at the exact place.

4. EXEMPT, and here is why each is exempt:

   - a token that is part of an ISO date (`YYYY-MM-DD`), a `YYYYMMDD` date, an
     `HH:MM` time, or a dotted version like `0.1.0`, decided by testing the
     token's SURROUNDING characters - a date component is not a measurement,
     and `2026` in `2026-09-20` is not a pageview count;
   - a token immediately preceded by `%` inside a word;
   - a bare list-bullet marker, which the regex can never see anyway.

5. NORMALISATION of a surviving token: strip a leading `+`, strip a trailing
   `%`, delete every `,` / U+00A0 / space, then `float()`. The token PASSES if
   its normalised form is in the accepted set of ANY source value. Otherwise it
   FAILS, and the report names the token, `line N offset M`, and the three
   numerically closest source values - so an operator can see at a glance
   whether the model wrote a stale number or a computed one.

DELIBERATELY NOT COVERED, and these belong in the runbook's "what a failure
means" list rather than being hidden here:

   - a number spelled in words ("півтора", "one hundred");
   - a number inside an embedded image, which no text reader can see;
   - **a percentage the model derived from two `metrics.json` values.** This is
     a real gap. A derived ratio is a new number, and property 1 will call it a
     novel number even though the model computed it honestly. The remedy is the
     interpretation file's rule, not a looser check.

Exit codes: 0 all four properties pass, 1 at least one fails, 2 a usage or
input problem. The tool's own problems are therefore distinguishable from the
answer's problems.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from collections.abc import Iterator, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

# Stamped into every regression stub, so a fixture promoted months later says
# which validator produced it. Bump on any change to the four properties.
VERSION = "0.1.0"

# The four EVAL-01 properties, in report order, printed in this order so a
# reader can diff two runs line for line. Adding a fifth property means adding
# it here and writing the check beside the others; the runbook documents this
# tuple as the contract.
PROPERTIES = (
    "numbers_present",
    "low_is_hypothesis",
    "as_of_present",
    "sources_and_limitations",
)

# MARKER CHECK, NOT A SEMANTIC ONE. A model that writes "зріс" in a sentence
# that also carries "гіпотеза" PASSES this property, and a model that writes a
# bare conclusion in a language this table does not cover FAILS for the wrong
# reason. Neither is a defect of the check: the human read is still the final
# word, which is exactly why the roadmap scopes EVAL-01 to `partial` rather
# than `full`. To cover another language, extend BOTH tuples - a hedge list
# without a matching assertion list would let a conclusion through.
#
# Lower-cased substrings, covering the two languages the report stage supports
# (`uk`, `en`). Ukrainian first, because the committed document language is
# Ukrainian.
HEDGE_MARKERS = (
    "гіпотез",
    "можливо",
    "схоже",
    "не впевн",
    "низьк",
    "low confidence",
    "hypothes",
    "possibly",
    "may ",
    "appears",
    "not certain",
    "unclear",
)

ASSERTION_MARKERS = (
    "зріс",
    "зростає",
    "росте",
    "впав",
    "падає",
    "підтвердж",
    "rising",
    "grew",
    "growing",
    "increased",
    "declin",
    "dropped",
)

# Property 4. Each group must MATCH and must have a non-blank, non-heading body
# after it, so an empty "## Джерела" heading is a failure rather than a pass.
# Case-insensitive; the `re.IGNORECASE | re.UNICODE` flags are what let a
# Cyrillic heading match without transliteration.
_SECTION_FLAGS = re.IGNORECASE | re.UNICODE
SECTION_PATTERNS: dict[str, tuple[str, ...]] = {
    "sources": (r"джерел", r"sources?", r"data source"),
    "limitations": (r"обмеження", r"limitations?", r"припущення"),
}

# One regex for every number the answer contains. Grouping separators are the
# three forms a human actually types: comma, no-break space, plain space.
NUMBER_PATTERN = re.compile(
    r"(?P<sign>[+-]?)(?P<int>\d[\d,  ]*)(?:\.(?P<frac>\d+))?(?P<pct>%)?"
)

# A date, a time, a compact date, or a dotted version: matched against the
# characters AROUND a token, never inside it, because the token regex already
# consumed the digits.
_DATE_CONTEXT = re.compile(
    r"(?:\d{4}-\d{1,2}-\d{1,2}|\d{8}|\d{1,2}:\d{2}|\d+\.\d+\.\d+)"
)
_SENTENCE_SPLIT = re.compile(r"[.!?\n]+")
_WORD_BOUNDARY_BEFORE = re.compile(r"[A-Za-zА-Яа-яІіЇїЄєҐґ0-9._%+-]$")
_ENCODING_TRIPLET = re.compile(r"%[0-9A-Fa-f]{2}")


@dataclass
class PropertyResult:
    """One property's verdict, and the detail that explains it."""

    name: str
    passed: bool
    detail: str = ""
    offending_token: str | None = None
    # True when the property PASSED because there was nothing to check. A vacuous
    # pass is printed as a NOTE so it is visible in the transcript rather than
    # indistinguishable from a real one.
    vacuous: bool = False
    excerpt: str = ""


@dataclass
class ValidationReport:
    """All four results plus the paths they were graded against."""

    results: list[PropertyResult] = field(default_factory=list)
    metrics_path: Path | None = None
    answer_path: Path | None = None
    metrics_sha256: str = ""
    answer_sha256: str = ""


# --------------------------------------------------------------------------
# Source-value collection
# --------------------------------------------------------------------------


def _numeric_leaves(node: Any, dates: set[str]) -> list[float]:
    """Every numeric leaf of the document, plus every date string, collected.

    `dates` is filled with the WHOLE date strings (`as_of`, `period.start`,
    `period.end`), never their components: a date component is not a
    measurement, and treating `2026` as a pageview count would make the check
    noisy on every date in the answer.
    """
    found: list[float] = []
    if isinstance(node, dict):
        for key, value in node.items():
            if key in {"as_of", "start", "end"} and isinstance(value, str):
                dates.add(value)
            else:
                found.extend(_numeric_leaves(value, dates))
    elif isinstance(node, list):
        for item in node:
            found.extend(_numeric_leaves(item, dates))
    elif isinstance(node, bool):
        pass
    elif isinstance(node, (int, float)):
        found.append(float(node))
    return found


def _accepted_forms(value: float) -> set[str]:
    """Every spelling of `value` this validator accepts. A CLOSED set.

    The list is fixed and total: grouping separators, a `+` sign, a `.1f`
    rendering and integral roundings. Nothing here widens a value, and nothing
    here introduces a tolerance.
    """
    forms: set[str] = set()
    forms.add(str(value))
    forms.add(f"{value:+}")
    forms.add(f"{value:+.1f}")
    forms.add(f"{value:.1f}")
    forms.add(f"{value:,}")
    forms.add(f"{value:,.1f}")
    forms.add(f"{value:,.0f}")
    if value.is_integer():
        forms.add(str(int(value)))
    forms.add(str(round(value, 0)))
    forms.add(str(round(value, 1)))
    grouped: set[str] = set()
    for form in forms:
        if "," in form:
            grouped.add(form.replace(",", " "))
            grouped.add(form.replace(",", " "))
    return forms | grouped


def _strip_separators(value: str) -> str:
    """Delete every grouping separator: `,`, no-break space and plain space."""
    for separator in (",", " ", " "):
        value = value.replace(separator, "")
    return value


def _normalise(token: str) -> float:
    """Strip the display decoration off a token and read it as a number."""
    cleaned = token.strip()
    if cleaned.startswith(("+", "-")):
        cleaned = cleaned[1:]
    cleaned = cleaned.rstrip("%")
    return float(_strip_separators(cleaned))


def _encoding_spans(text: str) -> list[tuple[int, int]]:
    """Character spans of every `%XX` percent-encoding triplet in the text.

    `references/CONTRACTS.md` §1 carries the Czech article slug verbatim in its
    encoded form, `P%C5%AFst_p%C5%99eru%C5%A1ovan%C3%BD`, and an answer quoting the
    article it analysed will quote it. The number regex reads `5%` out of `C5%AF`
    and `1` out of `%A1`, so without this rule every honest answer that names
    the article fails property 1 on its own slug.

    The overlap test is narrow by construction: a real percentage's token ENDS
    at its `%`, so it never intersects the triplet that starts there, while a
    token inside a triplet always does. `16.7%` and `50% done` stay checked.
    """
    return [(match.start(), match.end()) for match in _ENCODING_TRIPLET.finditer(text)]


def _is_exempt(text: str, match: re.Match[str], encodings: Sequence[tuple[int, int]]) -> bool:
    """Whether a matched token is a date, a time, a version, or an encoding."""
    start, end = match.span()
    window = text[max(0, start - 12) : min(len(text), end + 12)]
    if _DATE_CONTEXT.search(window):
        return True
    if any(start < encoding_end and encoding_start < end for encoding_start, encoding_end in encodings):
        return True
    prefix = text[:start]
    if prefix and _WORD_BOUNDARY_BEFORE.search(prefix) and prefix.endswith("%"):
        return True
    return False


def _nearest(value: float, pool: Sequence[float]) -> list[float]:
    """The three DISTINCT pool values numerically closest to `value`.

    Deduplicated because `metrics.json` carries a value twice wherever a
    `clean` variant repeats its `pct`/`abs` - reporting "5.7, 5.7, 3.5" would
    spend two of three slots on one number.
    """
    distinct = sorted(set(pool))
    return sorted(distinct, key=lambda candidate: abs(candidate - value))[:3]


def _iter_tokens(text: str) -> Iterator[tuple[str, re.Match[str]]]:
    """Yield `(token, match)` for every non-exempt number, with its position."""
    encodings = _encoding_spans(text)
    for match in NUMBER_PATTERN.finditer(text):
        if _is_exempt(text, match, encodings):
            continue
        yield match.group(0), match



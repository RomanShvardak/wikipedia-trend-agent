# Property 4. Each group must MATCH and must have a non-blank, non-heading body
# after it, so an empty "## Джерела" heading is a failure rather than a pass.
# Case-insensitive; the `re.IGNORECASE | re.UNICODE` flags are what let a
# Cyrillic heading match without transliteration.
_SECTION_FLAGS = re.IGNORECASE | re.UNICODE
SECTION_PATTERNS: dict[str, tuple[str, ...]] = {
    "sources": (r"джерел", r"sources?", r"data source"),
    "limitations": (r"обмеження", r"limitations?", r"припущення"),
}

# One regex for every number the answer contains. Grouping separators are the
# three forms a human actually types: comma, no-break space, plain space.
#
# The sign class carries U+2212 MINUS SIGN alongside ASCII `-` (FINDING-04).
# It is a different code point, so without it the regex never matched it as a
# sign at all and `−38.5%` was read as the POSITIVE `38.5`. `-` is listed first
# so the alternation prefers it where both are possible.
NUMBER_PATTERN = re.compile(
    r"(?P<sign>[-+−]?)(?P<int>\d[\d, ]*)(?:\.(?P<frac>\d+))?(?P<pct>%)?"
)


# A date, a time, a compact date, or a dotted version: matched against the
# characters AROUND a token, never inside it, because the token regex already
# consumed the digits.
_DATE_CONTEXT = re.compile(
    r"(?:\d{4}-\d{1,2}-\d{1,2}|\d{8}|\d{1,2}:\d{2}|\d+\.\d+\.\d+)"
)
_SENTENCE_SPLIT = re.compile(r"[.!?\n]+")
_WORD_BOUNDARY_BEFORE = re.compile(r"[A-Za-zА-Яа-яІіЇїЄєҐґ0-9._%+-]$")
_ENCODING_TRIPLET = re.compile(r"%[0-9A-Fa-f]{2}")

# U+2212 MINUS SIGN. A typographic minus is what a word processor and a
# Ukrainian keyboard produce, and it is a DIFFERENT code point from ASCII `-`,
# so the token regex never saw it as a sign at all: `-52.5%` failed as `-52.5`
# while `−52.5%` was read as the positive `52.5`.
_TYPOGRAPHIC_MINUS = "\u2212"

# A bare integer inside reason prose. Deliberately narrower than
# `NUMBER_PATTERN`: no sign, no decimal, no percent, no grouping. A reason
# string must not be able to inject a value the tool would not otherwise have
# produced as a source. Only the two rubric keys above are scanned, so no
# free-form string elsewhere in `metrics.json` becomes a number source.
_REASON_INTEGER = re.compile(r"\d+")


@dataclass
class PropertyResult:
    """One property's verdict, and the detail that explains it."""

    name: str
    passed: bool
    detail: str = ""
    offending_token: str | None = None
    # True when the property PASSED because there was nothing to check. A vacuous
    # pass is printed as a NOTE so it is visible in the transcript rather than
    # indistinguishable from a real one.
    vacuous: bool = False
    excerpt: str = ""


@dataclass
class ValidationReport:
    """All four results plus the paths they were graded against."""

    results: list[PropertyResult] = field(default_factory=list)
    metrics_path: Path | None = None
    answer_path: Path | None = None
    metrics_sha256: str = ""
    answer_sha256: str = ""



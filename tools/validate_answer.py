def check_numbers(text: str, metrics: dict[str, Any]) -> PropertyResult:
    """Property 1: every number in the answer is present in `metrics.json`."""
    dates: set[str] = set()
    pool = _numeric_leaves(metrics, dates)
    accepted: set[float] = set()
    for value in pool:
        for form in _accepted_forms(value):
            # The accepted side is normalised by `_normalise` ITSELF, not by a
            # hand-inlined variant of it. The FINDING-04 fix added signed,
            # unsigned and comma-decimal spellings, and the two sides must
            # agree on all three: a pool built with `_strip_separators` alone
            # would read the accepted form "38,5" as 385 while the answer's
            # identical token was read as 38.5, and every comma-decimal
            # spelling would fail against its own source value.
            try:
                accepted.add(_normalise(form))
            except ValueError:  # pragma: no cover - a form that is not numeric
                continue
    # The date strings themselves are legitimate content and are compared as
    # WHOLE STRINGS - a date is not a number, so it never goes through
    # `_normalise`. (Its components are exempt by rule 4 anyway; this is the
    # second, independent way the same content is accepted.)
    accepted_dates = {_strip_separators(value) for value in dates}

    lines = text.splitlines()
    for token, match in _iter_tokens(text):
        if _strip_separators(token.lstrip("+").rstrip("%")) in accepted_dates:
            continue
        try:
            value = _normalise(token)
        except ValueError:
            continue
        if value in accepted:
            continue
        line_number = text.count("\n", 0, match.start()) + 1
        line_start = text.rfind("\n", 0, match.start()) + 1
        offset = match.start() - line_start
        context = lines[line_number - 1].strip() if line_number <= len(lines) else ""
        nearest = ", ".join(str(value_) for value_ in _nearest(value, pool))
        return PropertyResult(
            name="numbers_present",
            passed=False,
            detail=(
                f"token {token!r} at line {line_number} offset {offset} matches no "
                f"metrics.json value; nearest source values: {nearest or 'none'}; "
                f"line reads: {context[:200]}"
            ),
            offending_token=token,
            excerpt=context[:400],
        )
    return PropertyResult(
        name="numbers_present",
        passed=True,
        detail=f"{len(pool)} source values, every number in the answer matched one",
    )


def check_low_is_hypothesis(text: str, metrics: dict[str, Any]) -> PropertyResult:
    """Property 2: a `low` series is phrased as a hypothesis, never a conclusion.

    A MARKER check, not a semantic one - see the module-level note on
    `HEDGE_MARKERS`. A `metrics.json` with no `low` series passes with the
    message `no low-confidence series to check`: a vacuous pass is STATED, not
    hidden, and the exit code is still 0.
    """
    lowered = text.casefold()
    low_series = [
        series for series in metrics.get("series", []) if series.get("confidence") == "low"
    ]
    if not low_series:
        return PropertyResult(
            name="low_is_hypothesis",
            passed=True,
            detail="no low-confidence series to check",
            vacuous=True,
        )

    sentences = [part.strip() for part in _SENTENCE_SPLIT.split(text) if part.strip()]
    for series in low_series:
        needles = [
            str(series.get("label", "")).casefold(),
            str(series.get("series_id", "")).casefold(),
        ]
        needles = [needle for needle in needles if needle]
        mentioning = [sentence for sentence in sentences if any(n in sentence.casefold() for n in needles)]
        series_id = str(series.get("series_id", "?"))
        if not mentioning:
            return PropertyResult(
                name="low_is_hypothesis",
                passed=False,
                detail=f"low series {series_id} is not mentioned at all",
                excerpt="",
            )
        hedged = [s for s in mentioning if any(m in s.casefold() for m in HEDGE_MARKERS)]
        if not hedged:
            unhedged = next(
                (
                    s
                    for s in mentioning
                    if any(m in s.casefold() for m in ASSERTION_MARKERS)
                ),
                mentioning[0],
            )
            return PropertyResult(
                name="low_is_hypothesis",
                passed=False,
                detail=(
                    f"low series {series_id} is mentioned but no sentence about it carries a "
                    f"hedge marker; it reads: {unhedged[:200]}"
                ),
                excerpt=unhedged[:400],
            )
        for sentence in mentioning:
            folded = sentence.casefold()
            asserted = any(marker in folded for marker in ASSERTION_MARKERS)
            hedged_here = any(marker in folded for marker in HEDGE_MARKERS)
            if asserted and not hedged_here:
                return PropertyResult(
                    name="low_is_hypothesis",
                    passed=False,
                    detail=(
                        f"low series {series_id} is asserted without a hedge in the same "
                        f"sentence: {sentence[:200]}"
                    ),
                    excerpt=sentence[:400],
                )
    del lowered
    return PropertyResult(
        name="low_is_hypothesis",
        passed=True,
        detail=f"{len(low_series)} low-confidence series, every mention hedged",
    )


def check_as_of_present(text: str, metrics: dict[str, Any]) -> PropertyResult:
    """Property 3: `as_of` is present, in its one canonical spelling.

    Unlike property 1, the `YYYYMMDD` form is NOT accepted here. This property
    is about the reader being able to tell how fresh the reading is, and a
    single canonical spelling is the point of it.
    """
    expected = str(metrics.get("as_of", ""))
    if not expected:
        return PropertyResult(
            name="as_of_present",
            passed=False,
            detail="metrics.json carries no as_of, so freshness cannot be stated",
        )
    if expected in text:
        return PropertyResult(
            name="as_of_present", passed=True, detail=f"as_of {expected} stated literally"
        )
    return PropertyResult(
        name="as_of_present",
        passed=False,
        detail=f"as_of {expected!r} does not appear in the answer, in any spelling",
        offending_token=expected,
    )


def _section_body(text: str, start: int) -> str:
    """The first non-blank, non-heading line after a heading match."""
    for line in text[start:].splitlines()[1:]:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        return stripped
    return ""


def check_sources_and_limitations(text: str, metrics: dict[str, Any]) -> PropertyResult:
    """Property 4: a sources section and a limitations section, both non-empty.

    A heading with an empty body is the failure this property exists to catch:
    "## Джерела" followed by nothing reads as compliance to a skim and is not.
    """
    del metrics
    missing: list[str] = []
    empty: list[str] = []
    for name, patterns in SECTION_PATTERNS.items():
        hit = None
        for pattern in patterns:
            compiled = re.compile(pattern, _SECTION_FLAGS)
            found = compiled.search(text)
            if found is not None:
                hit = found
                break
        if hit is None:
            missing.append(name)
        elif not _section_body(text, hit.start()):
            empty.append(name)
    if missing:
        return PropertyResult(
            name="sources_and_limitations",
            passed=False,
            detail=f"no section found for: {', '.join(missing)}",
        )
    if empty:
        return PropertyResult(
            name="sources_and_limitations",
            passed=False,
            detail=f"section heading present but the body is empty for: {', '.join(empty)}",
        )
    return PropertyResult(
        name="sources_and_limitations",
        passed=True,
        detail="sources and limitations sections both present and non-empty",
    )


CHECKS = {
    "numbers_present": check_numbers,
    "low_is_hypothesis": check_low_is_hypothesis,
    "as_of_present": check_as_of_present,
    "sources_and_limitations": check_sources_and_limitations,
}



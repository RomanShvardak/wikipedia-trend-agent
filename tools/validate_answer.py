# MARKER CHECK, NOT A SEMANTIC ONE. A model that writes "зріс" in a sentence
# that also carries "гіпотеза" PASSES this property, and a model that writes a
# bare conclusion in a language this table does not cover FAILS for the wrong
# reason. Neither is a defect of the check: the human read is still the final
# word, which is exactly why the roadmap scopes EVAL-01 to `partial` rather
# than `full`. To cover another language, extend BOTH tuples - a hedge list
# without a matching assertion list would let a conclusion through.
#

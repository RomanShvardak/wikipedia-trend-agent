def _numeric_leaves(node: Any, dates: set[str]) -> list[float]:
    """Every numeric leaf of the document, plus every date string, collected.

    `dates` is filled with the WHOLE date strings (`as_of`, `period.start`,
    `period.end`), never their components: a date component is not a
    measurement, and treating `2026` as a pageview count would make the check
    noisy on every date in the answer.

    A STRING leaf is also scanned for integers, but only under a key that the
    rubric populates with prose. `confidence_reasons` and `seasonality.note`
    are strings by contract, and SKILL.md requires the answer to quote them
    verbatim - so `period at least 91 days` and `no recurring peak months
    identified` are mandatory content. Before this, `_numeric_leaves` skipped
    every string, and an honest answer that obeyed the quoting rule failed
    property 1 on the rubric's own thresholds (FINDING-04).

    The scan is a bounded integer pattern, deliberately NOT the full
    `NUMBER_PATTERN`: a reason string must not be able to inject a decimal,
    a sign or a percent into the source set that the rest of the tool would
    not itself have produced. Only the keys below are scanned, so no
    free-form string elsewhere in `metrics.json` is a number source.
    """
    found: list[float] = []
    if isinstance(node, dict):
        for key, value in node.items():
            if key in {"as_of", "start", "end"} and isinstance(value, str):
                dates.add(value)
            elif key == "confidence_reasons" and isinstance(value, list):
                # A list of rubric strings, one per scoring line.
                found.extend(
                    float(number)
                    for entry in value
                    if isinstance(entry, str)
                    for number in _REASON_INTEGER.findall(entry)
                )
            elif key == "note" and isinstance(value, str):
                # `seasonality.note` is the sibling case: one rubric string.
                found.extend(float(number) for number in _REASON_INTEGER.findall(value))
            else:
                found.extend(_numeric_leaves(value, dates))
    elif isinstance(node, list):
        for item in node:
            found.extend(_numeric_leaves(item, dates))
    elif isinstance(node, bool):
        pass
    elif isinstance(node, (int, float)):
        found.append(float(node))
    return found


def _accepted_forms(value: float) -> set[str]:
    """Every spelling of `value` this validator accepts. A CLOSED set.

    The list is fixed and total: grouping separators, a `+` sign, a `.1f`
    rendering and integral roundings. Nothing here widens a value, and nothing
    here introduces a tolerance.

    Two additions over the original list, both of which are new SPELLINGS of an
    existing source value rather than a widened tolerance - the closed-set
    property this docstring asserts is intact:

    * the COMMA decimal rendering, because the document language is Ukrainian
      and a comma is the decimal separator there;
    * nothing else. In particular there is deliberately NO unsigned form of a
      negative value, even though "fell by 38.5%" is how a person writes a
      decline. A bare `38.5` and a `+38.5` are the SAME token to this
      checker, so accepting the unsigned magnitude would let an answer claim a
      38.5% INCREASE against a source value of -38.5 - precisely the sign error
      property 1 exists to catch, and no surrounding-word analysis can tell
      the two apart here. A decline is therefore quoted WITH its sign, which is
      what `manual.md` A.8 already does.

    All were touched for FINDING-04, where a declining series had no quotable
    spelling at all. A tolerance band is still forbidden: 16.7 does not pass
    because 16.6 would.
    """
    forms: set[str] = set()
    forms.add(str(value))
    forms.add(f"{value:+}")
    forms.add(f"{value:+.1f}")
    forms.add(f"{value:.1f}")
    forms.add(f"{value:,}")
    forms.add(f"{value:,.1f}")
    forms.add(f"{value:,.0f}")
    if value.is_integer():
        forms.add(str(int(value)))
    forms.add(str(round(value, 0)))
    forms.add(str(round(value, 1)))
    grouped: set[str] = set()
    for form in forms:
        if "," in form:
            grouped.add(form.replace(",", " "))
            grouped.add(form.replace(",", " "))
    # The comma-as-decimal rendering is added only where a comma is a DECIMAL
    # separator, which is a single comma followed by one or two digits. Adding
    # it to a grouped form (`1,720`) would invent a 1.720 reading, so each
    # ungrouped form is converted explicitly instead.
    decimal_comma: set[str] = set()
    for form in forms:
        if "." in form and "," not in form:
            decimal_comma.add(form.replace(".", ","))
    return forms | grouped | decimal_comma



def _strip_separators(value: str) -> str:
    """Delete every grouping separator: `,`, no-break space and plain space."""
    for separator in (",", " ", " "):
        value = value.replace(separator, "")
    return value


def _normalise(token: str) -> float:
    """Strip the display decoration off a token and read it as a number.

    The SIGN IS KEPT, and this is the FINDING-04 fix. The previous version
    stripped a leading `+` or `-` alike, so `-52.5` was read as `52.5` while
    `_accepted_forms` only ever emitted signed spellings of a negative value -
    the value's own form was not in the accepted set, and no answer could quote
    a decline. Only `+` is dropped now, because it carries no information that
    the magnitude does not.

    U+2212 is folded to ASCII `-` first: it is a different code point, so the
    token regex never saw it as a sign at all and `−52.5%` was read as the
    POSITIVE `52.5`.

    A COMMA is read as a decimal separator only when it cannot be a thousands
    group: a real group is preceded by a digit and followed by exactly three.
    `52,5` is 52.5 (the Ukrainian spelling); `1,720` is 1720.
    """
    cleaned = token.strip().replace(_TYPOGRAPHIC_MINUS, "-")
    if cleaned.startswith("+"):
        cleaned = cleaned[1:]
    cleaned = cleaned.rstrip("%")
    if "," in cleaned and not re.fullmatch(r"\d{1,3}(,\d{3})+(\.\d+)?", cleaned):
        cleaned = cleaned.replace(",", ".")
    return float(_strip_separators(cleaned))


def _encoding_spans(text: str) -> list[tuple[int, int]]:
    """Character spans of every `%XX` percent-encoding triplet in the text.

    `references/CONTRACTS.md` §1 carries the Czech article slug verbatim in its
    encoded form, `P%C5%AFst_p%C5%99eru%C5%A1ovan%C3%BD`, and an answer quoting the
    article it analysed will quote it. The number regex reads `5%` out of `C5%AF`
    and `1` out of `%A1`, so without this rule every honest answer that names
    the article fails property 1 on its own slug.

    The overlap test is narrow by construction: a real percentage's token ENDS
    at its `%`, so it never intersects the triplet that starts there, while a
    token inside a triplet always does. `16.7%` and `50% done` stay checked.
    """
    return [(match.start(), match.end()) for match in _ENCODING_TRIPLET.finditer(text)]


def _is_exempt(text: str, match: re.Match[str], encodings: Sequence[tuple[int, int]]) -> bool:
    """Whether a matched token is a date, a time, a version, or an encoding."""
    start, end = match.span()
    window = text[max(0, start - 12) : min(len(text), end + 12)]
    if _DATE_CONTEXT.search(window):
        return True
    if any(start < encoding_end and encoding_start < end for encoding_start, encoding_end in encodings):
        return True
    prefix = text[:start]
    if prefix and _WORD_BOUNDARY_BEFORE.search(prefix) and prefix.endswith("%"):
        return True
    # FINDING-04: digits inside a proper name. `N8n` is an article title, and
    # the answer has to be able to name the article it analysed - the same
    # reason a percent-encoded slug is exempt above.
    #
    # The rule is deliberately narrow: a LETTER on BOTH sides. A measurement in
    # prose is always bounded by whitespace or punctuation, so this cannot
    # exempt a real number. It is NOT "any alphabetic neighbour", which would
    # silently exempt every figure in a sentence; `test_the_proper_name_exemption_is_narrow`
    # pins that half of the claim by requiring a letter-bounded token with no
    # letter neighbour to still be checked.
    if (
        start > 0
        and end < len(text)
        and text[start - 1].isalpha()
        and text[end].isalpha()
    ):
        return True
    return False


def _nearest(value: float, pool: Sequence[float]) -> list[float]:
    """The three DISTINCT pool values numerically closest to `value`.

    Deduplicated because `metrics.json` carries a value twice wherever a
    `clean` variant repeats its `pct`/`abs` - reporting "5.7, 5.7, 3.5" would
    spend two of three slots on one number.
    """
    distinct = sorted(set(pool))
    return sorted(distinct, key=lambda candidate: abs(candidate - value))[:3]


def _iter_tokens(text: str) -> Iterator[tuple[str, re.Match[str]]]:
    """Yield `(token, match)` for every non-exempt number, with its position."""
    encodings = _encoding_spans(text)
    for match in NUMBER_PATTERN.finditer(text):
        if _is_exempt(text, match, encodings):
            continue
        yield match.group(0), match



"""Grade a cheap model's answer against that run's `metrics.json` (EVAL-01).

WHY `tools/` AND NOT `scripts/`. This is not a pipeline stage. It runs *after*
the report, on a file the model produced; it has no `--spec`/`--out` contract;
it is never in `run_all`'s four-stage sequence; and `scripts/` is the directory
the agentskills runtime loads, the one `mypy scripts --strict` treats as the
frozen stage surface, and the one the contract tests enumerate. A fifth CLI
there would make `scripts/` mean two things. It also imports **nothing from
the skill** - it is a reader - so it needs no `sys.path` shim and no `common`
import, which is what makes the no-network proof a one-line AST check.

It reads `metrics.json` and NOTHING else. Not `charts.json`, not `report.md`,
not `series.csv`. The answer is graded against the same single source of truth
the report was written from (ANAL-06, `references/CONTRACTS.md` §2), which is
the only way "the model did not invent a number" is a mechanical claim rather
than a promise.

===========================================================================
THE NUMBER RULE, IN FULL (an unstated rule is a noisy check)
===========================================================================

1. The SOURCE SET is every numeric leaf of `metrics.json`, plus `as_of` and
   every `period.start` / `period.end` **as whole strings** - the dates
   themselves, not their components. A date is not a measurement.

2. For each source number `v` the ACCEPTED FORMS are precomputed and the list
   is CLOSED - it is a fixed set of spellings, not a tolerance:

       str(v)                      f"{v:+.1f}"        f"{v:,.1f}"
       f"{v:+}"                    f"{v:.1f}"         f"{v:,.0f}"
       str(int(v))  (integral v)   str(round(v, 0))   str(round(v, 1))

   plus a SPACE-grouped variant of each grouped form, generated by replacing
   `,` with U+00A0 and then with U+0020 (so `1 720 628` is a spelling of
   1720628), plus a COMMA-DECIMAL variant of each ungrouped form (`38,5` is a
   spelling of 38.5, which the Ukrainian document language needs).
   **There is no tolerance band.** A band is precisely what lets a wrong number
   through: if 16.7 passes because 16.6 would also pass, the check is
   decorative.

   A NEGATIVE value is quoted WITH its sign. There is deliberately no unsigned
   form: a bare `38.5` and a `+38.5` are the same token here, so accepting the
   magnitude would let an answer claim a 38.5% increase against a source of
   -38.5 - the sign error this property exists to catch.

3. TOKENISATION is one regex: an optional sign (`-`, `+`, or U+2212), a digit,
   then digits with optional `,` / U+00A0 / space grouping, then an optional
   `.` plus digits, then an optional `%`. A comma is a DECIMAL separator only
   when it cannot be a thousands group (preceded by a digit, followed by
   exactly three), so `52,5` is 52.5 and `1,720` is 1720. The line number and
   character offset of every match are captured so a failure can point at the
   exact place.

4. EXEMPT, and here is why each is exempt:

   - a token that is part of an ISO date (`YYYY-MM-DD`), a `YYYYMMDD` date, an
     `HH:MM` time, or a dotted version like `0.1.0`, decided by testing the
     token's SURROUNDING characters - a date component is not a measurement,
     and `2026` in `2026-09-20` is not a pageview count;
   - a token immediately preceded by `%` inside a word;
   - a token inside a `%XX` percent-encoding triplet, so a Czech or Ukrainian
     slug can be quoted verbatim;
   - a token bounded by a LETTER on both sides, so the article `N8n` can be
     named. A measurement in prose is always bounded by whitespace or
     punctuation, so this cannot reach a real figure;
   - a bare list-bullet marker, which the regex can never see anyway.

5. NORMALISATION of a surviving token: fold U+2212 to ASCII `-`, strip a
   leading `+` (but NOT a leading `-`), strip a trailing `%`, delete every `,`
   / U+00A0 / space that is a thousands group, then `float()`. The token
   PASSES if its normalised form is in the accepted set of ANY source value.
   Otherwise it FAILS, and the report names the token, `line N offset M`, and
   the three numerically closest source values - so an operator can see at a
   glance whether the model wrote a stale number or a computed one.

6. THE SOURCE SET ALSO READS THE RUBRIC PROSE. `confidence_reasons` (a list of
   strings) and `seasonality.note` are quoted verbatim by contract, so the
   integers inside them are legitimate sources: `period at least 91 days` and
   `fewer than two aligned 365-day halves are available` are mandatory content
   that property 1 must not fail. The scan is a bare digit run — no sign, no
   decimal, no percent — so a reason string cannot inject a value the tool
   would not itself have produced, and only those two keys are read.

DELIBERATELY NOT COVERED, and these belong in the runbook's "what a failure
means" list rather than being hidden here:

   - a number spelled in words ("півтора", "one hundred");
   - a number inside an embedded image, which no text reader can see;
   - **a percentage the model derived from two `metrics.json` values.** This is
     a real gap. A derived ratio is a new number, and property 1 will call it a
     novel number even though the model computed it honestly. The remedy is the
     interpretation file's rule, not a looser check.

Exit codes: 0 all four properties pass, 1 at least one fails, 2 a usage or
input problem. The tool's own problems are therefore distinguishable from the
answer's problems.
"""

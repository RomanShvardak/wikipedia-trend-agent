STUB_KEYS = (
    "version",
    "property",
    "metrics_sha256",
    "answer_sha256",
    "answer_filename",
    "detail",
    "offending_token",
    "created_from_metrics",
    "answer_excerpt",
)


def _write_stub(report: ValidationReport, result: PropertyResult, out_dir: Path) -> Path:
    """Write the promotion-shaped regression stub for one failing property.

    The shape is deliberately promotion-ready: a real failure becomes
    `tests/fixtures/eval/fail-<property>.example.json` by copying this file and
    replacing the excerpt, with NO edit to the schema. `metrics_sha256` is the
    binding field - a fixture that cannot be tied to the document it graded is
    not a regression fixture.
    """
    target_dir = out_dir / "eval" / "regression"
    target_dir.mkdir(parents=True, exist_ok=True)
    path = target_dir / f"{result.name}.example.json"
    document = {
        "version": VERSION,
        "property": result.name,
        "metrics_sha256": report.metrics_sha256,
        "answer_sha256": report.answer_sha256,
        "answer_filename": report.answer_path.name if report.answer_path else "",
        "detail": result.detail,
        "offending_token": result.offending_token,
        "created_from_metrics": str(report.metrics_path) if report.metrics_path else "",
        "answer_excerpt": result.excerpt[:400],
    }
    temporary = path.with_name(f".{path.name}.tmp")
    with temporary.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(document, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    os.replace(temporary, path)
    return path



def validate(answer_text: str, metrics: dict[str, Any]) -> list[PropertyResult]:
    """Run all four properties, ALWAYS in `PROPERTIES` order.

    A silent property is an unchecked property, so the order and the count are
    part of the contract rather than an accident of the dict.
    """
    results: list[PropertyResult] = []
    for name in PROPERTIES:
        results.append(CHECKS[name](answer_text, metrics))
    return results


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Grade a cheap model's answer against that run's metrics.json (EVAL-01).",
        epilog=(
            "Exit 0 = every property passed. Exit 1 = at least one property failed. "
            "Exit 2 = a usage or input problem. This tool never calls a model and "
            "never touches the network; the live cheap-model run is the owner's step, "
            "and the runbook is in README.md."
        ),
    )
    parser.add_argument("--answer", required=True, help="the model's answer file (Markdown or text)")
    parser.add_argument("--out", required=True, help="the pipeline output directory holding metrics.json")
    parser.add_argument("--quiet", action="store_true", help="suppress PASS lines; keep FAIL lines")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Grade one answer file. Returns 0, 1 or 2 - see the module docstring."""
    args = _parser().parse_args(argv)

    answer_path = Path(args.answer)
    metrics_path = Path(args.out) / "metrics.json"
    for path, label in ((answer_path, "answer"), (metrics_path, "metrics.json")):
        if not path.is_file():
            print(f"validate_answer: {label} not found: {path}", file=sys.stderr)
            return 2
    try:
        answer_bytes = answer_path.read_bytes()
        metrics_bytes = metrics_path.read_bytes()
    except OSError as error:
        print(f"validate_answer: could not read an input: {error}", file=sys.stderr)
        return 2
    try:
        metrics = json.loads(metrics_bytes.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        print(f"validate_answer: metrics.json is not readable JSON: {error}", file=sys.stderr)
        return 2
    if not isinstance(metrics, dict):
        print("validate_answer: metrics.json must be a JSON object", file=sys.stderr)
        return 2
    try:
        answer_text = answer_bytes.decode("utf-8")
    except UnicodeDecodeError as error:
        print(f"validate_answer: the answer file is not UTF-8: {error}", file=sys.stderr)
        return 2

    report = ValidationReport(
        metrics_path=metrics_path,
        answer_path=answer_path,
        metrics_sha256=hashlib.sha256(metrics_bytes).hexdigest(),
        answer_sha256=hashlib.sha256(answer_bytes).hexdigest(),
    )
    report.results = validate(answer_text, metrics)

    failures = [result for result in report.results if not result.passed]
    for result in report.results:
        if result.passed:
            if not args.quiet:
                print(f"PASS {result.name}")
        else:
            print(f"FAIL {result.name}: {result.detail}")
    for result in report.results:
        if result.vacuous:
            print(f"NOTE {result.name}: {result.detail}")

    for result in failures:
        stub = _write_stub(report, result, Path(args.out))
        print(f"wrote regression stub: {stub}")

    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
